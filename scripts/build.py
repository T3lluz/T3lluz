#!/usr/bin/env python3
"""Build the profile from live GitHub data: the images go to dist/, the text to README.md.

    GITHUB_TOKEN=... python3 scripts/build.py              # fetch and build
    python3 scripts/build.py --cache .profile-cache.json   # reuse a local API snapshot
    python3 scripts/build.py --base dist --readme preview.md   # point the README at local images

The images are published on the `images` branch (see .github/workflows/profile.yml), so main only
gets a commit when the README text changes. Standard library only.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import detect
import panels
from config import INTRO, LINKS, USERNAME
from data import Profile, load_profile
from theme import M, V, row

ROOT = Path(__file__).resolve().parent.parent
RAW = f"https://raw.githubusercontent.com/{USERNAME}/{USERNAME}/images"
PROFILE = f"https://github.com/{USERNAME}"


# Rows come in two shapes. Wide viewports get the side-by-side one. The second range is a phone
# held sideways or a small tablet, where GitHub's page is one column and wide enough again.
WIDE = "(min-width: 1012px), (min-width: 600px) and (max-width: 767px)"
ROWS = {
    "now": "The repos I committed to most in the last 30 days, and my latest commits",
    "year": "Commits, pull requests and weekly contributions over the last 12 months, and the languages I wrote",
    "tools": "Frameworks and tools used in my recent repos, and my pull requests to other people's repos",
}


def images(p: Profile, snake_svg: str | None) -> dict[str, str]:
    row_a, row_b = 300, 282
    row_c, build_chips = panels.bottom_row(p)
    rows = {
        "now": row(panels.projects(p, row_a), panels.log(p, row_a), row_a, ROWS["now"]),
        "year": row(panels.activity(p, row_b), panels.languages(p, row_b), row_b, ROWS["year"]),
        "tools": row(panels.stack(p, row_c, build_chips), panels.upstream(p, row_c), row_c, ROWS["tools"], foot=M - V),
    }
    out = {"hero.svg": panels.hero(p)}
    for name, (wide, tall) in rows.items():
        out[f"{name}.svg"] = wide
        out[f"{name}-phone.svg"] = tall
    if snake_svg:
        out["snake.svg"] = panels.snake(p, snake_svg)
    for label, (markup, _, _) in panels.buttons().items():
        out[f"btn-{label.lower()}.svg"] = markup
    return out


def _listing(names: list[str]) -> str:
    return names[0] if len(names) == 1 else f"{', '.join(names[:-1])} and {names[-1]}"


def readme(p: Profile, base: str) -> str:
    def image(name: str, alt: str, href: str) -> str:
        return f'<a href="{href}"><img src="{base}/{name}.svg" width="100%" align="top" alt="{alt}" /></a>'

    def pair(name: str, href: str) -> str:
        return (f'<a href="{href}"><picture><source media="{WIDE}" srcset="{base}/{name}.svg" />'
                f'<img src="{base}/{name}-phone.svg" width="100%" align="top" alt="{ROWS[name]}" /></picture></a>')

    links = []
    for label, _, _, url in LINKS:
        _, width, height = panels.buttons()[label]
        img = f'<img src="{base}/btn-{label.lower()}.svg" width="{width}" height="{height}" alt="{label}" />'
        links.append(f'  <a href="{url}">{img}</a>' if url else f"  {img}")

    working = _listing([r.name for r, _ in p.active[:3]]) if p.active else "nothing public right now"
    projects = "\n".join(f"- [{r.name}]({r.url})" + (f": {r.description}" if r.description else "") for r, _ in p.active)
    pulls = "\n".join(f"- [{pr['repo']}]({pr['url']}): {pr['title']} ({pr['state']})" for pr in p.upstream)
    stack = "\n".join(
        f"- {group.capitalize()}: {', '.join(detect.TECH[k][0] for k in p.stack[group])}"
        for group in detect.GROUPS if p.stack.get(group)
    )
    languages = ", ".join(name for name, _ in p.languages)

    return f"""<!-- Generated by scripts/build.py from live GitHub data. Edit scripts/, not this file. -->

<div align="center">

<!-- Every image is as wide as the page and top-aligned, so the dark backgrounds join into
     one surface. Rows of two windows switch to a stacked image on phones. -->
<p>
  {image("hero", f"{p.login}. {INTRO} Working on {working}.", PROFILE)}
  {pair("now", f"{PROFILE}?tab=repositories")}
  {pair("year", PROFILE)}
  {image("snake", "Snake eating my contribution graph", PROFILE)}
  {pair("tools", f"https://github.com/search?q=is%3Apr+author%3A{USERNAME}+-user%3A{USERNAME}&type=pullrequests")}
</p>

<p>
{chr(10).join(links)}
</p>

</div>

<details>
<summary>Text version, with links</summary>

**Working on**

{projects or "- Nothing public this month."}

**Pull requests elsewhere**

{pulls or "- None lately."}

**Stack**

- Languages, last 90 days: {languages}
{stack}

</details>

<div align="center">
  <sub>Rebuilt every hour from the GitHub API by <a href="{PROFILE}/{USERNAME}/tree/main/scripts">scripts/build.py</a>.</sub>
</div>
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cache", type=Path, help="read/write the raw API responses here")
    parser.add_argument("--snake", type=Path, default=ROOT / "build" / "snake.svg", help="snake SVG from generate-snake-animation")
    parser.add_argument("--out", type=Path, default=ROOT / "dist", help="where the images go")
    parser.add_argument("--base", default=RAW, help="URL or path the README loads the images from")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    parser.add_argument("--snake-options", action="store_true", help="print the snake colours as a query string and exit")
    args = parser.parse_args()
    if args.snake_options:
        print(panels.SNAKE_OPTIONS)
        return

    p = load_profile(args.cache)
    if not args.snake.exists():
        print(f"no snake at {args.snake}, leaving snake.svg as it is")
    outputs = {args.out / name: content for name, content in
               images(p, args.snake.read_text(encoding="utf-8") if args.snake.exists() else None).items()}
    outputs[args.readme] = readme(p, args.base)
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {len(outputs) - 1} images to {args.out} and {args.readme}")


if __name__ == "__main__":
    main()
